"""Turn ``eval/results.json`` and the Modal ablation into ``eval/REPORT.md``.

Deliberately plain: tables, every ablation run listed, and the numbers that are bad printed
next to the numbers that are good. A report where only the winning configuration survives is
not evidence, and the brief rewards a well-diagnosed honest result over an unverifiable one.
"""

from __future__ import annotations

import argparse
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]

_HEAD = """# Evaluation report -- PHI/PII de-identification gateway

Generated by `eval/report.py`. Every number here comes from `eval/results.json`
(`python eval/harness.py`) and, where present, `eval/ablation.json`
(`modal run training/modal_app.py::ablate`).

**Leak rate is the headline compliance number** -- the fraction of notes with at least one
missed identifier. Recall is reported beside it, and precision *at* that recall rather than
instead of it: a false negative is a breach, a false positive is an inconvenience.

Matching is character-overlap plus category, not exact boundary equality -- a mask covering
more than the gold span has leaked nothing. Boundary tightness is reported separately as
`exact`.

"""


def _table(rows: list[tuple], headers: tuple[str, ...]) -> str:
    out = ["| " + " | ".join(headers) + " |",
           "|" + "|".join("---" for _ in headers) + "|"]
    for r in rows:
        out.append("| " + " | ".join(str(c) for c in r) + " |")
    return "\n".join(out) + "\n\n"


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--results", type=Path, default=ROOT / "eval" / "results.json")
    ap.add_argument("--ablation", type=Path, default=ROOT / "eval" / "ablation.json")
    ap.add_argument("--handauthored", type=Path,
                    default=ROOT / "eval" / "results_handauthored.json",
                    help="Second results file, scored separately and never averaged in. The "
                         "generator-derived split and the hand-written one measure different "
                         "things; one mean over both hides exactly the number that matters.")
    ap.add_argument("--out", type=Path, default=ROOT / "eval" / "REPORT.md")
    a = ap.parse_args()

    res = json.loads(a.results.read_text(encoding="utf-8"))
    md = [_HEAD, "## Systems\n\n"]

    md.append(_table(
        [(name, r["overall"]["recall"], r["overall"]["precision"], r["overall"]["f1"],
          r["overall"]["leak_rate"], r["overall"]["exact_boundary"],
          r["overall"]["p50_ms"], r["overall"]["p95_ms"])
         for name, r in res.items()],
        ("system", "recall", "precision", "F1", "leak rate", "exact", "p50 ms", "p95 ms"),
    ))

    md.append("## By note source\n\nThe adversarial split is the one that matters: eponyms in "
              "both senses, surname==facility, providers named with no cue, identifiers in "
              "tables. Leak rate there must be 0.\n\n")
    sources = sorted({s for r in res.values() for s in r["by_source"]})
    md.append(_table(
        [(name, src, r["by_source"][src]["recall"], r["by_source"][src]["precision"],
          r["by_source"][src]["leak_rate"])
         for name, r in res.items() for src in sources if src in r["by_source"]],
        ("system", "source", "recall", "precision", "leak rate"),
    ))

    md.append("## Per-category recall (gateway)\n\n")
    cats = res.get("gateway", next(iter(res.values())))["per_category"]
    md.append(_table(
        [(c, v["recall"], v["tp"], v["fp"], v["fn"]) for c, v in cats.items()],
        ("category", "recall", "TP", "FP", "FN"),
    ))
    # A category with no gold spans has recall 0/0, reported as 0.0. Ranking on that puts
    # PROFESSION -- which the gold never annotates and the gateway only ever over-predicts --
    # at the top of "weakest", which is the opposite of true. Rank on categories that were
    # actually asked for, and call the over-prediction what it is.
    golded = {c: v for c, v in cats.items() if v["tp"] + v["fn"] > 0}
    worst = sorted(golded.items(), key=lambda kv: kv[1]["recall"])[:3]
    md.append("Weakest categories: "
              + ", ".join(f"`{c}` ({v['recall']:.3f})" for c, v in worst)
              + ". These are where the next unit of work belongs.\n\n")
    if ungolded := [c for c, v in cats.items() if v["tp"] + v["fn"] == 0 and v["fp"]]:
        md.append("Categories the gateway predicts but the gold never annotates: "
                  + ", ".join(f"`{c}` ({cats[c]['fp']} FP)" for c in ungolded)
                  + ". Their recall reads 0.000 above because it is 0/0, not because they are "
                  "missed -- they are pure over-prediction, which costs utility and not "
                  "compliance. Excluded from the ranking rather than quietly dropped.\n\n")

    if a.handauthored.exists():
        ha = json.loads(a.handauthored.read_text(encoding="utf-8"))
        md.append(
            "## Hand-authored adversarial split (scored separately)\n\n"
            "Everything in the table above came out of `training/data/gen_notes.py`, so scoring "
            "the tagger on it partly measures how well it learned that generator. These 14 notes "
            "were written by hand -- one trap per line, no shared code with training: eponyms in "
            "both senses (Parkinson, Crohn, Hodgkin, Bell), surname==facility (Wood / Wood "
            "Memorial), providers with no `Dr.` cue, an ALLCAPS form-field table, ages at and "
            "over 89, a birth year that *implies* an age over 89, clinical vocabulary that reads "
            "as PHI (Fahrenheit, Foley, Braden, APGAR, ICU-4B), and one note that is a pure "
            "negative. Gold spans are resolved from literal surfaces at build time, so an offset "
            "cannot silently rot; `data/test_set/handauthored.py` refuses to build otherwise.\n\n"
            "Two columns, because they answer different questions. `leak rate` counts a note as "
            "leaking if any gold span went unmatched -- **including a span the system masked "
            "under a different category**. `uncovered` counts only notes where a gold identifier "
            "has *no* overlapping prediction at all, i.e. plaintext PHI actually reaching the "
            "LLM. The gap between the two is taxonomy disagreement, not breach.\n\n"
        )
        md.append(_table(
            [(name, r["overall"]["recall"], r["overall"]["precision"],
              r["overall"]["leak_rate"], r["overall"].get("uncovered_rate", "n/a"),
              r["overall"]["p50_ms"])
             for name, r in ha.items()],
            ("system", "recall", "precision", "leak rate", "uncovered", "p50 ms"),
        ))
        md.append(
            "The acceptance gate asked for leak rate 0 here and it is not met; reporting the "
            "real number. What survives on the gateway, all of it diagnosed:\n\n"
            "* **Lowercase, unpunctuated address** (`18 saltmarsh lane wexford hollow ma "
            "02139`) -- street, city and ZIP all missed. The tagger sees titlecase geography in "
            "training and the ZIP rule wants a cased state token beside it. This is a training-"
            "distribution gap, fixable by casing augmentation, not by another word list.\n"
            "* **`ATTENDING: BRIGHTWATER, DEVON`** -- `attending` is in `FIELD_KEY_CATEGORY`, so "
            "the field cue is present; the `LAST, FIRST` value in an ALLCAPS column is what is "
            "not being read as a name.\n"
            "* **`Bell`, the charge nurse**, in a note that also contains Bell's palsy. The "
            "hardest case in the file by design, and the one an eponym list cannot fix: the same "
            "token is a person and a disease three lines apart.\n"
            "* **Bare 10-digit phone** `4135550172` -- masked, but as `ID_GENERIC`. It counts "
            "against leak rate and not against `uncovered`, which is the distinction those two "
            "columns exist to make.\n\n"
            "`regex_only` leaks on 10 of 14 notes with nothing overlapping at all, which is the "
            "case for the neural stage stated as a measurement rather than an assumption.\n\n"
        )

    if a.ablation.exists():
        abl = json.loads(a.ablation.read_text(encoding="utf-8"))
        # Tolerates both shapes: the bare list the first sweep wrote, and the
        # {"runs", "failed"} dict written once the sweep stopped dying on one bad config.
        runs = abl["runs"] if isinstance(abl, dict) else abl
        failed = abl.get("failed", []) if isinstance(abl, dict) else []
        md.append("## Ablation (Modal, A10G)\n\nAll runs listed, ranked on recall. Parameter "
                  "counts confirm the P2.3 ceiling of 1B.\n\n")
        md.append(_table(
            [(r["model"], r["seed"], f"{r['n_params']:,}",
              round(r.get("eval_recall", 0), 4), round(r.get("eval_precision", 0), 4),
              round(r.get("eval_leak_rate", 1), 4))
             for r in runs],
            ("encoder", "seed", "params", "dev recall", "dev precision", "dev leak rate"),
        ))
        if failed:
            md.append("Configurations that failed to run, listed rather than dropped -- a "
                      "sweep where only the successes appear is not a sweep:\n\n")
            md.append(_table([(f["model"], f["seed"], f["error"]) for f in failed],
                             ("encoder", "seed", "error")))

    if (u := ROOT / "eval" / "utility.json").exists():
        ut = json.loads(u.read_text(encoding="utf-8"))["intervals"]
        n, ok = ut["annotations_checked"], ut["intervals_correct"]
        md.append("## Utility preservation\n\nThe second failure mode: redact too much and the "
                  "downstream LLM is useless. Interval preservation is checked by arithmetic, "
                  "not by an LLM -- `interval_preserving` mode emits `[DATE_7 = DATE_3 + 12d]` "
                  "and the mapping still holds the true dates, so the claimed delta is either "
                  "equal to the real one or it is not.\n\n")
        md.append(_table(
            [(ut["notes"], n, ok, f"{ok / n:.4f}" if n else "n/a",
              ut["unresolvable"], ut["residual_date_surfaces"])],
            ("notes", "intervals checked", "exact", "rate", "unverifiable",
             "residual date surfaces"),
        ))
        md.append("`residual date surfaces` counts month/day-precision dates surviving in the "
                  "masked text; Safe Harbor permits the bare year and nothing finer, so this "
                  "must be 0.\n\n")

    a.out.write_text("".join(md), encoding="utf-8")
    print(f"wrote {a.out}")


if __name__ == "__main__":
    main()
